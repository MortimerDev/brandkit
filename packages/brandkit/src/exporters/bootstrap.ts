import type { Brandkit } from "../types.js";

/**
 * Sass variables for Bootstrap 5.3. Load them before Bootstrap:
 *
 *   @import "brand";
 *   @import "bootstrap/scss/bootstrap";
 *
 * Covers theme colours, body and border colours for light and dark colour
 * modes (`data-bs-theme="dark"`), fonts, radii and shadows.
 */
export function exportBootstrap(kit: Brandkit): string {
  const l = kit.semantic.light;
  const d = kit.semantic.dark;
  const n = kit.scales.neutral;
  const { typography: t } = kit;

  const vars: [string, string][] = [
    ["primary", l.primary.hex],
    ["secondary", n[600].hex],
    ["success", l.success.hex],
    ["info", l.info.hex],
    ["warning", l.warning.hex],
    ["danger", l.danger.hex],
    ["light", n[100].hex],
    ["dark", n[900].hex],
    ["body-bg", l.background.hex],
    ["body-color", l.foreground.hex],
    ["border-color", l.border.hex],
    ["link-color", l.link.hex],
    ["link-hover-color", l["primary-hover"].hex],
    ["min-contrast-ratio", "4.5"],
    ["font-family-sans-serif", t.families.body],
    ["headings-font-family", t.families.heading],
    ["font-family-monospace", t.families.mono],
    ["headings-font-weight", String(t.weights.heading)],
    ["border-radius-sm", kit.radius.sm],
    ["border-radius", kit.radius.md],
    ["border-radius-lg", kit.radius.lg],
    ["border-radius-xl", kit.radius.xl],
    ["box-shadow-sm", kit.shadow.sm],
    ["box-shadow", kit.shadow.md],
    ["box-shadow-lg", kit.shadow.lg],
    ["body-bg-dark", d.background.hex],
    ["body-color-dark", d.foreground.hex],
    ["body-secondary-bg-dark", d.surface.hex],
    ["body-tertiary-bg-dark", d.muted.hex],
    ["border-color-dark", d.border.hex],
    ["link-color-dark", d.link.hex],
    ["link-hover-color-dark", d["primary-hover"].hex],
  ];

  const header = [
    `// Brand kit for ${kit.meta.name}, generated by @mortimerdev/brandkit.`,
    '// Import before "bootstrap/scss/bootstrap". Fonts load separately:',
    `// ${t.googleFontsUrl}`,
  ];
  return `${header.join("\n")}\n\n${vars.map(([k, val]) => `$${k}: ${val};`).join("\n")}\n`;
}
