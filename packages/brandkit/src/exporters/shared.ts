import { type Color, formatOklch } from "../color.js";
import { SCALE_STEPS } from "../palette.js";
import {
  type Brandkit,
  type ScaleName,
  SEMANTIC_ROLES,
  type SemanticColors,
  type SemanticRole,
} from "../types.js";

export type ColorFormat = "oklch" | "hex";

export const SCALE_NAMES: ScaleName[] = [
  "primary",
  "accent",
  "neutral",
  "success",
  "warning",
  "danger",
  "info",
];

export function colorValue(color: Color, format: ColorFormat): string {
  return format === "hex" ? color.hex : formatOklch(color.oklch);
}

export function banner(kit: Brandkit, extra?: string): string {
  const lines = [`Brand kit for ${kit.meta.name}, generated by @mortimerdev/brandkit.`];
  if (extra) lines.push(extra);
  return `/*\n${lines.map((l) => ` * ${l}`).join("\n")}\n */`;
}

/** Spacing keys such as "0.5" become CSS-safe "0_5". */
export function cssKey(key: string): string {
  return key.replace(/\./g, "_");
}

export interface ScaleEntry {
  scale: ScaleName;
  step: number;
  color: Color;
}

export function scaleEntries(kit: Brandkit): ScaleEntry[] {
  return SCALE_NAMES.flatMap((scale) =>
    SCALE_STEPS.map((step) => ({ scale, step, color: kit.scales[scale][step] })),
  );
}

export function semanticEntries(
  colors: SemanticColors,
): [SemanticRole, SemanticColors[SemanticRole]][] {
  return SEMANTIC_ROLES.map((role) => [role, colors[role]]);
}

export function block(selector: string, declarations: string[], indent = ""): string {
  const inner = declarations.map((d) => `${indent}  ${d}`).join("\n");
  return `${indent}${selector} {\n${inner}\n${indent}}`;
}
