import type { Brandkit, SemanticColors } from "../types.js";
import { SCALE_NAMES, semanticEntries } from "./shared.js";
import { SCALE_STEPS } from "../palette.js";

type Token = { $type: string; $value: unknown; $description?: string };
type Group = { [key: string]: Token | Group | string };

function splitStack(stack: string): string[] {
  return stack.split(",").map((part) => part.trim().replace(/^"|"$/g, ""));
}

const SHADOW_LAYER =
  /(-?[\d.]+(?:px)?) (-?[\d.]+(?:px)?) (-?[\d.]+(?:px)?) (-?[\d.]+(?:px)?) (rgb\([^)]*\))/g;

function shadowValue(css: string) {
  return [...css.matchAll(SHADOW_LAYER)].map(([, x, y, blur, spread, color]) => ({
    color,
    offsetX: x,
    offsetY: y,
    blur,
    spread,
  }));
}

/**
 * W3C Design Tokens (DTCG) JSON for Figma plugins, Tokens Studio and
 * Style Dictionary. Semantic colours alias the scale tokens, with light and
 * dark modes as sibling groups. Values use the widely supported string form
 * (hex colours, "1rem" dimensions).
 */
export function exportDtcg(kit: Brandkit): Group {
  const color: Group = {};
  for (const scale of SCALE_NAMES) {
    const group: Group = {};
    for (const step of SCALE_STEPS) {
      group[String(step)] = { $type: "color", $value: kit.scales[scale][step].hex };
    }
    color[scale] = group;
  }

  const semantic = (colors: SemanticColors): Group =>
    Object.fromEntries(
      semanticEntries(colors).map(([role, c]) => [
        role,
        {
          $type: "color",
          $value: c.ref ? `{color.${c.ref.scale}.${c.ref.step}}` : c.hex,
        } satisfies Token,
      ]),
    );

  const { typography: t } = kit;
  const dimensionGroup = (values: Record<string, string>): Group =>
    Object.fromEntries(
      Object.entries(values).map(([k, val]) => [k, { $type: "dimension", $value: val }]),
    );

  return {
    $description: `Brand kit for ${kit.meta.name}, generated by @mortimerdev/brandkit.`,
    color,
    semantic: { light: semantic(kit.semantic.light), dark: semantic(kit.semantic.dark) },
    font: {
      family: {
        heading: { $type: "fontFamily", $value: splitStack(t.families.heading) },
        body: { $type: "fontFamily", $value: splitStack(t.families.body) },
        mono: { $type: "fontFamily", $value: splitStack(t.families.mono) },
      },
      weight: Object.fromEntries(
        Object.entries(t.weights).map(([k, w]) => [k, { $type: "fontWeight", $value: w }]),
      ),
      size: dimensionGroup(
        Object.fromEntries(Object.entries(t.scale).map(([k, s]) => [k, s.size])),
      ),
      lineHeight: Object.fromEntries(
        Object.entries(t.scale).map(([k, s]) => [
          k,
          { $type: "number", $value: Number(s.lineHeight) },
        ]),
      ),
    },
    space: dimensionGroup(kit.spacing),
    radius: dimensionGroup(kit.radius),
    shadow: Object.fromEntries(
      Object.entries(kit.shadow).map(([k, s]) => [k, { $type: "shadow", $value: shadowValue(s) }]),
    ),
  };
}

export function exportDtcgJson(kit: Brandkit): string {
  return `${JSON.stringify(exportDtcg(kit), null, 2)}\n`;
}
