import type { Brandkit, SemanticColors } from "../types.js";

export interface VuetifyThemeDefinition {
  dark: boolean;
  colors: Record<string, string>;
  variables: Record<string, string | number>;
}

export interface VuetifyThemeOptions {
  defaultTheme: "light" | "dark";
  themes: { light: VuetifyThemeDefinition; dark: VuetifyThemeDefinition };
}

function theme(kit: Brandkit, colors: SemanticColors, dark: boolean): VuetifyThemeDefinition {
  const step = (s: keyof Brandkit["scales"]["primary"]) => kit.scales.primary[s].hex;
  return {
    dark,
    colors: {
      background: colors.background.hex,
      surface: dark ? colors.surface.hex : colors.background.hex,
      "surface-bright": colors.surface.hex,
      "surface-variant": colors.muted.hex,
      "on-surface-variant": colors["muted-foreground"].hex,
      primary: colors.primary.hex,
      "primary-darken-1": dark ? step(500) : colors["primary-hover"].hex,
      secondary: colors.accent.hex,
      error: colors.danger.hex,
      info: colors.info.hex,
      success: colors.success.hex,
      warning: colors.warning.hex,
      "on-background": colors.foreground.hex,
      "on-surface": colors.foreground.hex,
      "on-primary": colors["primary-foreground"].hex,
      "on-secondary": colors["accent-foreground"].hex,
      "on-error": colors["danger-foreground"].hex,
      "on-info": colors["info-foreground"].hex,
      "on-success": colors["success-foreground"].hex,
      "on-warning": colors["warning-foreground"].hex,
    },
    variables: {
      "border-color": colors.border.hex,
      "border-opacity": 1,
    },
  };
}

/** Vuetify 3 theme options object: `createVuetify({ theme: exportVuetify(kit) })`. */
export function exportVuetify(kit: Brandkit): VuetifyThemeOptions {
  return {
    defaultTheme: "light",
    themes: {
      light: theme(kit, kit.semantic.light, false),
      dark: theme(kit, kit.semantic.dark, true),
    },
  };
}

/** The same theme as a ready-to-save module (brand-theme.js). */
export function exportVuetifyModule(kit: Brandkit): string {
  const json = JSON.stringify(exportVuetify(kit), null, 2);
  return [
    `// Brand kit for ${kit.meta.name}, generated by @mortimerdev/brandkit.`,
    "// Usage: createVuetify({ theme: brandTheme })",
    `// Fonts: load ${kit.typography.googleFontsUrl}`,
    `// and set $body-font-family: ${kit.typography.families.body} in your Vuetify Sass settings.`,
    "",
    `export const brandTheme = ${json};`,
    "",
    "export default brandTheme;",
    "",
  ].join("\n");
}
